const clamp = (value) => Math.min(1, Math.max(0, value));

function hexToHsl(hex) {
  const input = hex.replace('#', '');
  const r = parseInt(input.slice(0, 2), 16) / 255;
  const g = parseInt(input.slice(2, 4), 16) / 255;
  const b = parseInt(input.slice(4, 6), 16) / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const delta = max - min;
  let hue = 0;
  let saturation = 0;
  const lightness = (max + min) / 2;

  if (delta !== 0) {
    saturation = delta / (1 - Math.abs(2 * lightness - 1));
    switch (max) {
      case r: hue = ((g - b) / delta) % 6; break;
      case g: hue = (b - r) / delta + 2; break;
      default: hue = (r - g) / delta + 4;
    }
    hue *= 60;
    if (hue < 0) hue += 360;
  }

  return `${Math.round(hue)} ${Math.round(saturation * 100)}% ${Math.round(lightness * 100)}%`;
}

function createTheme({
  id, name, emoji, description, mode,
  primary, action = primary, secondary, accent, accentForeground,
  background, surface, text, mutedText, softSurface, border, header,
  cardRadius, buttonRadius,
  headingFont, bodyFont = '"DM Sans", sans-serif',
  icon, shadow, buttonShadow,
  // Extended multicolor vars
  highlight, terracotta, sage, mint, coral, teal, gold, plum, lavender, seafoam,
}) {
  const primaryForeground = mode === 'dark' ? '#191C23' : '#FFFFFF';
  const hsl = (color) => hexToHsl(color);
  const effectiveAccentForeground = accentForeground || text;

  return {
    id, name, emoji, description, mode,
    primary, action, secondary, accent,
    bg: background, surface,
    cssVars: {
      '--background': hsl(background),
      '--foreground': hsl(text),
      '--card': hsl(surface),
      '--card-foreground': hsl(text),
      '--popover': hsl(surface),
      '--popover-foreground': hsl(text),
      '--primary': hsl(action),
      '--primary-foreground': hsl(primaryForeground),
      '--secondary': hsl(softSurface),
      '--secondary-foreground': hsl(text),
      '--muted': hsl(softSurface),
      '--muted-foreground': hsl(mutedText),
      '--accent': hsl(accent),
      '--accent-foreground': hsl(effectiveAccentForeground),
      '--destructive': '0 72% 51%',
      '--destructive-foreground': '0 0% 98%',
      '--border': hsl(border),
      '--input': hsl(border),
      '--ring': hsl(accent),
      '--chart-1': hsl(accent),
      '--chart-2': hsl(primary),
      '--chart-3': hsl(secondary),
      '--chart-4': hsl('#48C9C1'),
      '--chart-5': hsl('#D27B56'),
      '--radius': cardRadius,
      '--font-heading': headingFont,
      '--font-body': bodyFont,
      '--font-display': headingFont,
      '--font-mono': 'ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace',
      '--sidebar-background': hsl(surface),
      '--sidebar-foreground': hsl(text),
      '--sidebar-primary': hsl(action),
      '--sidebar-primary-foreground': hsl(primaryForeground),
      '--sidebar-accent': hsl(softSurface),
      '--sidebar-accent-foreground': hsl(text),
      '--sidebar-border': hsl(border),
      '--sidebar-ring': hsl(accent),
      '--card-shadow': shadow,
      '--card-icon': icon,
      '--theme-id': id,
      '--theme-primary': primary,
      '--theme-action-color': action,
      '--theme-secondary': secondary,
      '--theme-accent': accent,
      '--theme-background': background,
      '--theme-surface': surface,
      '--theme-text': text,
      '--theme-muted-text': mutedText,
      '--theme-soft-surface': softSurface,
      '--theme-border': border,
      '--theme-header-bg': header,
      '--theme-header-border': border,
      '--theme-card-radius': cardRadius,
      '--theme-button-radius': buttonRadius,
      '--theme-pill-radius': '999px',
      '--theme-card-shadow': shadow,
      '--theme-button-shadow': buttonShadow,
      '--theme-heading-font': headingFont,
      '--theme-body-font': bodyFont,
      // Extended theme color tokens
      '--theme-highlight': highlight || accent,
      '--theme-terracotta': terracotta || secondary,
      '--theme-sage': sage || softSurface,
      '--theme-mint': mint || softSurface,
      '--theme-coral': coral || accent,
      '--theme-teal': teal || secondary,
      '--theme-gold': gold || accent,
      '--theme-plum': plum || secondary,
      '--theme-lavender': lavender || softSurface,
      '--theme-seafoam': seafoam || softSurface,
    },
  };
}

